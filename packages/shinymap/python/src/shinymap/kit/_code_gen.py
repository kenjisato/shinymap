"""Code generation and one-shot conversion utilities.

This module provides:
- convert(): One-shot SVG/JSON to shinymap JSON conversion
- apply_mapping(): Apply a mapping dict to convert an outline
- generate_code(): Generate Python code for reproducible conversions
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from ..outline import Outline


def convert(
    input_path: Path | str,
    output_path: Path | str | None = None,
    relabel: dict[str, str | list[str]] | None = None,
    overlay_ids: list[str] | None = None,
    underlay_ids: list[str] | None = None,
    hidden_ids: list[str] | None = None,
    annotation_ids: list[str] | None = None,
    lines_as_path_ids: list[str] | None = None,
    metadata: dict[str, Any] | None = None,
    extract_viewbox: bool = True,
) -> dict[str, Any]:
    """Convert SVG or JSON file to shinymap JSON format.

    One-shot conversion that loads an SVG/JSON file and applies transformations.

    Args:
        input_path: Path to input SVG or JSON file
        output_path: Optional path to write JSON output
        relabel: Dict mapping new_id to old_id(s) for relabeling/merging
        overlay_ids: List of region IDs to mark as overlays
        underlay_ids: List of region IDs to mark as underlays
        hidden_ids: List of region IDs to mark as hidden
        annotation_ids: List of region IDs to mark as annotations
        lines_as_path_ids: List of region IDs to mark as lines (stroke-only)
        metadata: Dict of metadata to merge
        extract_viewbox: If True, extract viewBox from SVG (ignored for JSON input)

    Returns:
        Dict in shinymap JSON format

    Examples:
        >>> from shinymap.kit import convert
        >>>
        >>> result = convert(
        ...     "map.svg",
        ...     "map.json",
        ...     relabel={"tokyo": "path_1", "hokkaido": ["path_2", "path_3"]},
        ...     overlay_ids=["_border"],
        ...     underlay_ids=["_background"],
        ...     hidden_ids=["_guides"],
        ...     lines_as_path_ids=["_divider"],
        ...     metadata={"source": "Custom SVG"},
        ... )
    """
    file_path = Path(input_path).expanduser()

    # Load based on file type
    if file_path.suffix.lower() == ".json":
        outline = Outline.from_json(file_path)
    else:
        outline = Outline.from_svg(file_path, extract_viewbox=extract_viewbox)

    # Apply transformations
    if relabel:
        outline = outline.relabel(relabel)
    if overlay_ids:
        outline = outline.move_layer("overlay", overlay_ids)
    if underlay_ids:
        outline = outline.move_layer("underlay", underlay_ids)
    if hidden_ids:
        outline = outline.move_layer("hidden", hidden_ids)
    if annotation_ids:
        outline = outline.move_layer("annotation", annotation_ids)
    if lines_as_path_ids:
        outline = outline.path_as_line(*lines_as_path_ids)
    if metadata:
        outline = outline.update_metadata(metadata)

    # Write output if requested
    if output_path:
        outline.to_json(output_path)

    return outline.to_dict()


def apply_mapping(outline: Outline, mapping: dict[str, Any]) -> Outline:
    """Apply a mapping dict to convert an outline.

    One-shot conversion that applies groups, layers, lines_as_path, and metadata
    from a mapping dictionary. Useful for batch conversion from a mapping file
    generated by the sketch app.

    Args:
        outline: Source outline to transform
        mapping: Mapping dict with optional keys:
            - groups: Dict mapping new_id to old_id(s) for relabeling
            - layers: Dict with "overlay", "underlay", "hidden" lists
            - lines_as_path: List of region IDs to treat as lines
            - metadata: Dict of metadata to merge

    Returns:
        New Outline with all transformations applied

    Examples:
        >>> from shinymap import Outline
        >>> from shinymap.kit import apply_mapping
        >>>
        >>> outline = Outline.from_svg("map.svg")
        >>> mapping = {
        ...     "groups": {
        ...         "hokkaido": ["path_1", "path_2"],
        ...         "tokyo": "path_4",
        ...     },
        ...     "layers": {
        ...         "overlay": ["_border"],
        ...         "hidden": ["_guides"],
        ...     },
        ...     "lines_as_path": ["_divider"],
        ...     "metadata": {"source": "...", "license": "..."},
        ... }
        >>> result = apply_mapping(outline, mapping)
    """
    result = outline

    # Apply groups (relabeling)
    groups = mapping.get("groups")
    if groups:
        result = result.relabel(groups)

    # Apply layers
    layers = mapping.get("layers")
    if layers:
        for layer_name, region_ids in layers.items():
            if region_ids:
                result = result.move_layer(layer_name, region_ids)

    # Apply lines_as_path
    lines_as_path = mapping.get("lines_as_path")
    if lines_as_path:
        result = result.path_as_line(*lines_as_path)

    # Apply metadata
    metadata = mapping.get("metadata")
    if metadata:
        result = result.update_metadata(metadata)

    return result


def generate_code(
    input_filename: str,
    output_filename: str,
    relabel: dict[str, str | list[str]] | None = None,
    overlay_ids: list[str] | None = None,
    underlay_ids: list[str] | None = None,
    hidden_ids: list[str] | None = None,
    annotation_ids: list[str] | None = None,
    lines_as_path_ids: list[str] | None = None,
    metadata: dict[str, str] | None = None,
) -> str:
    """Generate Python code for the conversion.

    Generates reproducible Python code using the fluent Outline API.

    Args:
        input_filename: Name of the input SVG/JSON file
        output_filename: Name of the output JSON file
        relabel: Dict mapping new_id to old_id(s)
        overlay_ids: List of region IDs to mark as overlays
        underlay_ids: List of region IDs to mark as underlays
        hidden_ids: List of region IDs to mark as hidden
        annotation_ids: List of region IDs to mark as annotations
        lines_as_path_ids: List of region IDs to mark as lines (stroke-only)
        metadata: Dict of metadata to include

    Returns:
        Python code as a string

    Examples:
        >>> code = generate_code(
        ...     "map.svg",
        ...     "map.json",
        ...     relabel={"tokyo": "path_1"},
        ...     overlay_ids=["_border"],
        ...     underlay_ids=["_background"],
        ...     lines_as_path_ids=["_divider"],
        ... )
        >>> print(code)  # doctest: +SKIP
        # Generated by shinymap kit
        from shinymap.kit import convert
        ...
    """
    lines = [
        "# Generated by shinymap kit",
        "from shinymap.kit import convert",
        "",
        "convert(",
        f'    "{input_filename}",',
        f'    "{output_filename}",',
    ]

    if relabel:
        lines.append("    relabel={")
        for new_id, old_id_or_ids in relabel.items():
            lines.append(f'        "{new_id}": {old_id_or_ids!r},')
        lines.append("    },")

    if overlay_ids:
        lines.append(f"    overlay_ids={overlay_ids!r},")

    if underlay_ids:
        lines.append(f"    underlay_ids={underlay_ids!r},")

    if hidden_ids:
        lines.append(f"    hidden_ids={hidden_ids!r},")

    if annotation_ids:
        lines.append(f"    annotation_ids={annotation_ids!r},")

    if lines_as_path_ids:
        lines.append(f"    lines_as_path_ids={lines_as_path_ids!r},")

    if metadata:
        lines.append("    metadata={")
        for key, value in metadata.items():
            lines.append(f'        "{key}": "{value}",')
        lines.append("    },")

    lines.append(")")

    return "\n".join(lines)
